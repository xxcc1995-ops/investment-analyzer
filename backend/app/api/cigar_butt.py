def get_hk_stock_realtime(code: str) -> dict:
    try:
        url = f"https://qt.gtimg.cn/q=r_hk{code}"
        headers = {
            "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36",
            "Referer": "https://stockapp.finance.qq.com/",
        }
        r = requests.get(url, headers=headers, timeout=10)
        r.encoding = "gbk"
        text = r.text
        if "=\"" not in text:
            return None
        data = text.split("\"")[1].split("~")
        if len(data) < 50:
            return None
        name = data[1]
        price = float(data[3]) if data[3] else 0
        change_pct = float(data[32]) if data[32] else 0
        pe = float(data[39]) if data[39] else 0
        market_cap = float(data[44]) if data[44] else 0
        dividend_yield = float(data[43]) if data[43] else 0
        if price <= 0:
            return None
        return {
            "code": code, "name": name, "price": price,
            "change_pct": change_pct, "pe": pe if pe > 0 else None,
            "pb": None, "roe": None,
            "market_cap": market_cap, "dividend_yield": dividend_yield,
        }
    except:
        return None


