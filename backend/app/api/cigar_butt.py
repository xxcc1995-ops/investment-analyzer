def get_hk_stocks_data() -> list:
    stocks = []
    for code in HK_STOCKS_LIST:
        data = get_hk_stock_realtime(code)
        if data:
            if code in HK_STOCKS_PB:
                data["pb"] = HK_STOCKS_PB[code]
            if code in HK_STOCKS_ROE:
                data["roe"] = HK_STOCKS_ROE[code]
            stocks.append(data)
    return stocks


@router.get("/screener")
def cigar_butt_screener(
    max_pe: float = 10,
    max_pb: float = 1.0,
    min_roe: float = 8.0,
    min_dividend: float = 3.0,
    min_market_cap: float = 10,
    top_n: int = 50
):
    stocks = get_hk_stocks_data()
    results = []
    for stock in stocks:
        pe = stock.get("pe") or 0
        pb = stock.get("pb") or 0
        roe = stock.get("roe") or 0
        dividend_yield = stock.get("dividend_yield") or 0
        market_cap = stock.get("market_cap") or 0
        if pe <= 0 or pe > max_pe:
            continue
        if pb <= 0 or pb > max_pb:
            continue
        if roe < min_roe:
            continue
        if dividend_yield < min_dividend:
            continue
        if market_cap < min_market_cap:
            continue
        criteria_met = []
        if pe <= max_pe:
            criteria_met.append("PE低估")
        if pb <= max_pb:
            criteria_met.append("PB低估")
        if roe >= min_roe:
            criteria_met.append("高ROE")
        if dividend_yield >= min_dividend:
            criteria_met.append("高股息")
        if market_cap >= 50:
            criteria_met.append("大市值")
        stock["criteria_met"] = criteria_met
        results.append(stock)
    results.sort(key=lambda x: x.get("pb") or 999)
    results = results[:top_n]
    return {
        "stocks": results,
        "total": len(results),
        "update_time": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "criteria": {
            "max_pe": max_pe, "max_pb": max_pb,
            "min_roe": min_roe, "min_dividend": min_dividend,
            "min_market_cap": min_market_cap,
        }
    }


